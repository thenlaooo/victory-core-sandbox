from rapidfuzz import fuzz

s1 = "Иванов Иван"
s2 = "Ивонов Иван"          # опечатка в одной букве
s3 = "Иван Иванов"          # переставлены местами слова
s4 = "Иван"                 # одно слово из двух
s5 = "Иванов Иван красноармеец" # добавилось лишнее слово

print("--- 1. fuzz.ratio (Строгое посимвольное сравнение) ---")
# Сравнивает строки «в лоб» от первого до последнего символа.
# Учитывает порядок символов и общую длину.
print(f"Опечатка: {fuzz.ratio(s1, s2):.1f}%")       # ~90% (хорошо)
print(f"Перестановка: {fuzz.ratio(s1, s3):.1f}%")   # ~45% (очень плохо, хотя человек понимает, что это один и тот же боец)

print("\n--- 2. fuzz.partial_ratio (Поиск подстроки) ---")
# Ищет самую похожую короткую подстроку внутри длинной строки.
# Идеально, когда пользователь ввел только фамилию, а в базе хранится полное ФИО.
print(f"Подстрока 'Иван' в 'Иванов Иван': {fuzz.partial_ratio(s4, s1):.1f}%") # 100%

print("\n--- 3. fuzz.token_sort_ratio (Сравнение с сортировкой слов) ---")
# Разбивает строку на отдельные слова («токены»), сортирует их по алфавиту и только потом сравнивает.
# "Иван Иванов" -> превращается в "иван иванов"
# "Иванов Иван" -> превращается в "иван иванов"
print(f"Перестановка слов: {fuzz.token_sort_ratio(s1, s3):.1f}%") # 100% (проблема перестановки решена!)

print("\n--- 4. fuzz.token_set_ratio (Сравнение множеств слов) ---")
# Самый мощный алгоритм для поиска по архивам.
# Он берет уникальные слова из обеих строк, находит их пересечение,
# отбрасывает дубликаты и лишний информационный мусор.
print(f"С лишними словами: {fuzz.token_set_ratio(s1, s5):.1f}%") # 100%